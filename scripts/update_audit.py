#!/usr/bin/env python3
"""Maintain #print axioms coverage of every project theorem and lemma."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def lean_code(source):
    """Mask comments and strings while preserving line and token boundaries."""
    result = []
    depth = 0
    quoted = False
    line_comment = False
    i = 0
    while i < len(source):
        pair = source[i:i + 2]
        char = source[i]
        if char == "\n":
            result.append(char)
            line_comment = False
            i += 1
            continue
        if line_comment:
            result.append(" ")
        elif depth:
            if pair == "/-":
                depth += 1
                result.append("  ")
                i += 2
                continue
            if pair == "-/":
                depth -= 1
                result.append("  ")
                i += 2
                continue
            result.append(" ")
        elif quoted:
            result.append(" ")
            if char == "\\":
                result.append(" ")
                i += 2
                continue
            if char == '"':
                quoted = False
        elif pair == "--":
            line_comment = True
            result.append("  ")
            i += 2
            continue
        elif pair == "/-":
            depth = 1
            result.append("  ")
            i += 2
            continue
        elif char == '"':
            quoted = True
            result.append(" ")
        else:
            result.append(char)
        i += 1
    return "".join(result)


def declaration_names(source):
    text = lean_code(source.read_text())
    namespaces = re.findall(r"^namespace ([A-Za-z0-9_.]+)$", text, re.M)
    declarations = re.findall(
        r"^(?:@\[[^\n]*\][ \t]*)*(?:theorem|lemma) ([A-Za-z0-9_.']+)(?=\s|\[|\{)",
        text, re.M,
    )
    if declarations and all(name.startswith("_root_.") for name in declarations):
        return [name.removeprefix("_root_.") for name in declarations]
    if len(namespaces) != 1 or any(name.startswith("_root_.") for name in declarations):
        raise ValueError(f"Audit requires one namespace or fully explicit root theorem names: {source}")
    return [f"{namespaces[0]}.{name}" for name in declarations]


def discover_names():
    names = []
    sources = sorted((ROOT / "PaperP1").rglob("*.lean")) + sorted(ROOT.glob("SolutionP1*.lean"))
    for source in sources:
        names.extend(declaration_names(source))
    if not names or len(names) != len(set(names)):
        raise ValueError("Empty or duplicate theorem inventory")
    return names


def inventory_content(names):
    return json.dumps(names, indent=2) + "\n"


def render(names):
    digest = hashlib.sha256(inventory_content(names).encode()).hexdigest()
    solutions = "".join(f"import {path.stem}\n" for path in sorted(ROOT.glob("SolutionP1*.lean")))
    return '''module

import PaperP1
''' + solutions + '''import Lean.Elab.Print

/-! Generated by scripts/update_audit.py. The separate JSON inventory lists
every substantive project theorem and lemma, including Solution wrappers,
discovered from its Lean source. Standalone Challenges are excluded and never
imported. This command
invokes Lean's own `#print axioms` once for each declaration. Keeping the names
as data avoids a generated Lean source longer than Palomar's 10,000-line limit.
-/

-- Inventory SHA-256: ''' + digest + '''

open Lean Elab Command in
run_cmd do
  let raw ← IO.FS.readFile "docs/axiom-audit-declarations.json"
  let .ok entries := Json.parse raw >>= Json.getArr?
    | throwError "Invalid audit inventory"
  let mut seen : Std.HashSet Name := {}
  for entry in entries do
    let .ok text := entry.getStr? | throwError "Invalid declaration name"
    let name := text.toName
    if seen.contains name then throwError "Duplicate audit declaration: {name}"
    seen := seen.insert name
    unless (← getEnv).contains name do throwError "Missing audit declaration: {name}"
    elabCommand (← `(command| #print axioms $(mkIdent name)))
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    names = discover_names()
    rendered = render(names)
    path = ROOT / "Audit.lean"
    inventory = ROOT / "docs/axiom-audit-declarations.json"
    if args.check:
        if path.read_text() != rendered or inventory.read_text() != inventory_content(names):
            raise SystemExit("Axiom audit is out of date; run python3 scripts/update_audit.py")
        print(f"Axiom audit covers all {len(names)} project theorems and lemmas.")
    else:
        path.write_text(rendered)
        inventory.write_text(inventory_content(names))
