#!/usr/bin/env python3
"""Maintain #print axioms coverage of every project theorem and lemma."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def lean_code(source):
    """Mask comments and strings while preserving line and token boundaries."""
    result = []
    depth = 0
    quoted = False
    line_comment = False
    i = 0
    while i < len(source):
        pair = source[i:i + 2]
        char = source[i]
        if char == "\n":
            result.append(char)
            line_comment = False
            i += 1
            continue
        if line_comment:
            result.append(" ")
        elif depth:
            if pair == "/-":
                depth += 1
                result.append("  ")
                i += 2
                continue
            if pair == "-/":
                depth -= 1
                result.append("  ")
                i += 2
                continue
            result.append(" ")
        elif quoted:
            result.append(" ")
            if char == "\\":
                result.append(" ")
                i += 2
                continue
            if char == '"':
                quoted = False
        elif pair == "--":
            line_comment = True
            result.append("  ")
            i += 2
            continue
        elif pair == "/-":
            depth = 1
            result.append("  ")
            i += 2
            continue
        elif char == '"':
            quoted = True
            result.append(" ")
        else:
            result.append(char)
        i += 1
    return "".join(result)


def render():
    names = []
    for source in sorted((ROOT / "PaperP1").rglob("*.lean")):
        text = lean_code(source.read_text())
        namespaces = re.findall(r"^namespace ([A-Za-z0-9_.]+)$", text, re.M)
        if len(namespaces) != 1:
            raise ValueError(f"Audit discovery requires one namespace per module: {source}")
        declarations = re.findall(
            r"^(?:@\[[^\n]*\][ \t]*)*(?:theorem|lemma) ([A-Za-z0-9_.']+)(?=\s|\[|\{)",
            text,
            re.M,
        )
        names.extend(f"{namespaces[0]}.{name}" for name in declarations)
    if not names or len(names) != len(set(names)):
        raise ValueError("Empty or duplicate theorem inventory")
    header = 'module\n\nimport PaperP1\n\n/-! Generated by scripts/update_audit.py; all project theorems and lemmas. -/\n\n'
    return header + "\n".join(f"#print axioms {name}" for name in names) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    path = ROOT / "Audit.lean"
    if args.check:
        if path.read_text() != rendered:
            raise SystemExit("Audit.lean is out of date; run python3 scripts/update_audit.py")
        print(f"Axiom audit covers all {rendered.count('#print axioms')} project theorems and lemmas.")
    else:
        path.write_text(rendered)
